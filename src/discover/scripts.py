FASTAPI_AST_SEARCH = (
    "import ast\n"
    "import json\n"
    "import pathlib\n"
    "import sys\n"
    "\n"
    "urls_file = pathlib.Path(sys.argv[1])\n"
    "tree = ast.parse(urls_file.read_text(encoding='utf-8'))\n"
    "url_routes = []\n"
    "\n"
    "HTTP_METHODS = {'get', 'post', 'put', 'delete', 'patch', 'options', 'head', 'trace'}\n"
    "\n"
    "def get_string(node):\n"
    "    if isinstance(node, ast.Constant) and isinstance(node.value, str):\n"
    "        return node.value\n"
    "    return None\n"
    "\n"
    "def get_keyword(node, name):\n"
    "    for keyword in node.keywords:\n"
    "        if keyword.arg == name:\n"
    "            return keyword.value\n"
    "    return None\n"
    "\n"
    "for node in ast.walk(tree):\n"
    "    if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):\n"
    "        continue\n"
    "\n"
    "    for decorator in node.decorator_list:\n"
    "        if not isinstance(decorator, ast.Call):\n"
    "            continue\n"
    "\n"
    "        func = decorator.func\n"
    "\n"
    "        if not isinstance(func, ast.Attribute):\n"
    "            continue\n"
    "\n"
    "        decorator_name = func.attr.lower()\n"
    "\n"
    "        if decorator_name not in HTTP_METHODS | {'api_route'}:\n"
    "            continue\n"
    "\n"
    "        # Extract route from positional or keyword argument\n"
    "        route = decorator.args[0] if decorator.args else get_keyword(decorator, 'path')\n"
    "        route = route or get_keyword(decorator, 'url')\n"
    "        route = get_string(route) if route else None\n"
    "\n"
    "        if route is None:\n"
    "            continue\n"
    "\n"
    "        # Extract HTTP methods\n"
    "        if decorator_name == 'api_route':\n"
    "            methods_node = get_keyword(decorator, 'methods')\n"
    "            methods = []\n"
    "\n"
    "            if isinstance(methods_node, (ast.List, ast.Tuple, ast.Set)):\n"
    "                methods = [get_string(item).upper() for item in methods_node.elts if get_string(item)]\n"
    "\n"
    "            if not methods:\n"
    "                methods = ['GET']\n"
    "        else:\n"
    "            methods = [decorator_name.upper()]\n"
    "\n"
    "        for method in methods:\n"
    "            url_routes.append({\n"
    "                'route': route,\n"
    "                'method': method\n"
    "            })\n"
    "\n"
    "# Remove duplicates while preserving order\n"
    "url_routes = list({(r['route'], r['method']): r for r in url_routes}.values())\n"
    "\n"
    "print(json.dumps(url_routes))\n"
)
